function letterHTML(text) {
  const linked = esc(text).replace("Formosan Association for Public Affairs (FAPA)", '<a href="https://fapa.org/">Formosan Association for Public Affairs (FAPA)</a>').replace(/\nhttps:\/\/fapa\.org\/$/, '\n<a href="https://fapa.org/">https://fapa.org/</a>');
  return linked.split("\n\n").map(p => `<p>${p.replace(/\n/g, "<br>")}</p>`).join("");
}
async function copyRich(text, btn) {
  const done = () => { const o = btn.textContent; btn.textContent = t("copied"); setTimeout(() => btn.textContent = o, 1400); };
  try {
    if (window.ClipboardItem) {
      const plain = text;
      await navigator.clipboard.write([new ClipboardItem({
        "text/html": new Blob([letterHTML(text)], { type: "text/html" }),
        "text/plain": new Blob([plain], { type: "text/plain" })
      })]);
      done(); return;
    }
  } catch (e) {}
  copyText(text, btn);
}
