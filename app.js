function applyLang() {
  const meta = PAGE_META[lang];
  const publicRoot = document.querySelector('link[hreflang="en"]').href;
  const pageURL = new URL(meta.path, publicRoot).href;
  const imageURL = new URL("assets/" + meta.image, publicRoot).href;
  document.documentElement.lang = meta.lang;
  document.title = meta.title;
  document.querySelector('link[rel="canonical"]').href = pageURL;
  const tags = {
    description: meta.description, "og:title": meta.title, "og:description": meta.description,
    "og:url": pageURL, "og:site_name": meta.siteName, "og:locale": meta.locale,
    "og:locale:alternate": PAGE_META[lang === "en" ? "zh" : "en"].locale,
    "og:image": imageURL, "og:image:alt": meta.imageAlt,
    "twitter:title": meta.title, "twitter:description": meta.description,
    "twitter:image": imageURL, "twitter:image:alt": meta.imageAlt
  };
  Object.entries(tags).forEach(([key, value]) => {
    document.querySelector(`meta[property="${key}"],meta[name="${key}"]`).content = value;
  });
  // Keep the current ZIP, role, query and hash while making the URL shareable.
  // file:// previews can still switch languages without changing their URL.
  if (location.protocol === "http:" || location.protocol === "https:") {
    const url = new URL(meta.path, SITE_ROOT);
    url.search = location.search;
    url.hash = location.hash;
    history.replaceState(null, "", url.href);
  }
  document.querySelectorAll("[data-i18n]").forEach(el => el.textContent = t(el.dataset.i18n));
  document.querySelectorAll("[data-i18n-html]").forEach(el => el.innerHTML = t(el.dataset.i18nHtml));
  document.querySelectorAll(".lang button").forEach(b => b.setAttribute("aria-pressed", String(b.dataset.lang === lang)));
  if (role && $("#roletext")) $("#roletext").textContent = t(role === "member" ? "roleMember" : "roleFriend");
  render();
}

async function copyText(text, btn) {
  const flash = (msg) => { const o = btn.textContent; btn.textContent = msg; setTimeout(() => btn.textContent = o, 1400); };
  try { await navigator.clipboard.writeText(text); flash(t("copied")); return; } catch (e) {}
  let ok = false;
  const ta = document.createElement("textarea");
  ta.value = text; ta.setAttribute("readonly", ""); ta.style.cssText = "position:fixed;top:0;left:0;opacity:0";
  document.body.appendChild(ta);
  try { ta.select(); ta.setSelectionRange(0, text.length); ok = document.execCommand("copy"); } catch (e) {}
  ta.remove();
  flash(t(ok ? "copied" : "copyManual"));
}

