#!/usr/bin/env node
// index.html owns the shared markup. Both entry points use the same JS/CSS.
// Run after editing index.html or page-meta.js; commit the generated zh-tw page.
const fs = require("node:fs");
const path = require("node:path");
const pages = require("../page-meta.js");
const root = path.join(__dirname, "..");
const source = fs.readFileSync(path.join(root, "index.html"), "utf8");
const base = source.match(/<link rel="alternate" hreflang="en" href="([^"]+)"/)[1];
const escape = s => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");

for (const [key, page] of Object.entries(pages)) {
  const url = base + page.path;
  const image = base + "assets/" + page.image;
  const tags = {
    description: page.description, "og:title": page.title, "og:description": page.description,
    "og:url": url, "og:site_name": page.siteName, "og:locale": page.locale,
    "og:locale:alternate": pages[key === "en" ? "zh" : "en"].locale,
    "og:image": image, "og:image:alt": page.imageAlt,
    "twitter:title": page.title, "twitter:description": page.description,
    "twitter:image": image, "twitter:image:alt": page.imageAlt
  };
  let html = source
    .replace(/<html lang="[^"]+">/, `<html lang="${page.lang}">`)
    .replace(/<title>[^<]*<\/title>/, `<title>${escape(page.title)}</title>`)
    .replace(/<link rel="canonical" href="[^"]+">/, `<link rel="canonical" href="${url}">`)
    .replace(/<meta (name|property)="([^"]+)" content="[^"]*">/g,
      (tag, attr, name) => name in tags ? `<meta ${attr}="${name}" content="${escape(tags[name])}">` : tag);
  if (page.path) {
    html = html.replace('<base href="./">', '<base href="../">');
    html = html.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by scripts/generate-pages.js; edit index.html instead. -->");
  }
  const output = path.join(root, page.path, "index.html");
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(output) || fs.readFileSync(output, "utf8") !== html) {
      throw new Error(`${output} is stale; run node scripts/generate-pages.js`);
    }
  } else {
    fs.mkdirSync(path.dirname(output), { recursive: true });
    fs.writeFileSync(output, html);
  }
}
console.log(process.argv.includes("--check") ? "Locale pages are in sync." : "Generated English and zh-TW entry points.");
